#!/usr/bin/env python3
"""Generate bt2446-resources.h, which embeds the effect into the binary.

Some hosts load plugins from <host>/plugins and only
resolve module data under <host>/data/plugins, so a data directory next to the
DLL is not guaranteed to exist and the effect has to ship inside the module.
"""

import io
import sys


def c_escape(text):
    out = []
    for ch in text:
        if ch == "\\":
            out.append("\\\\")
        elif ch == '"':
            out.append('\\"')
        elif ch == "\t":
            out.append("\\t")
        elif ord(ch) < 0x20:
            continue
        else:
            out.append(ch)
    return "".join(out)


def main():
    if len(sys.argv) != 3:
        sys.exit("usage: gen_resources.py <effect> <output-header>")

    effect_path, out_path = sys.argv[1:3]

    with io.open(effect_path, "r", encoding="utf-8") as f:
        effect = f.read().replace("\r\n", "\n")

    lines = ["/* Generated by src/gen_resources.py - do not edit. */", ""]
    lines.append("static const char BT2446_EFFECT_SOURCE[] =")
    for src_line in effect.split("\n"):
        lines.append('\t"%s\\n"' % c_escape(src_line))
    lines[-1] = lines[-1] + ";"
    lines.append("")

    with io.open(out_path, "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(lines))


if __name__ == "__main__":
    main()
